// Snapshot the user's existing combat shader; adapt transport, not mechanics.
// Re-run deliberately when updating the upstream mechanics revision.
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL, fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const upstream=path.resolve(process.argv[2] || '/home/aaron-ma/yazpads_warlock_sim');
const src=path.join(upstream,'threejs_webgl_des/src');
const model=await import(pathToFileURL(path.join(src,'model.js')));
const kernel=await import(pathToFileURL(path.join(src,'kernel.js')));
const destination=path.join(root,'sim/classes/warlock/generated');
fs.mkdirSync(destination,{recursive:true});
const hashes={};
for(const name of ['model.js','kernel.js']) hashes[name]=createHash('sha256').update(fs.readFileSync(path.join(src,name))).digest('hex');
function replaceOnce(text,expression,replacement){
 const matches=[...text.matchAll(new RegExp(expression.source,expression.flags.includes('g')?expression.flags:expression.flags+'g'))];
 if(matches.length!==1) throw Error('Upstream transport anchor changed: '+expression);
 return text.replace(expression,replacement);
}
for(const detailed of [false,true]){
 const words=detailed?model.COMPACT_WORDS:16;
 let shader=kernel.buildFragment(detailed);
 shader=replaceOnce(shader,/precision highp float;[\s\S]*?uniform uint eventBudget;/,`#version 450
layout(local_size_x=64, local_size_y=1, local_size_z=1) in;
layout(std430) readonly buffer Configs { uint configData[]; };
layout(std430) readonly buffer Parameters { uint parameters[]; };
layout(std430) writeonly buffer Results { uint resultData[]; };
#define numConfigs parameters[0]
#define fightsPerConfig parameters[1]
#define seed parameters[2]
#define offset parameters[3]
#define count parameters[4]
#define eventBudget parameters[5]
const uint mode=0u;`);
 shader=replaceOnce(shader,/uint getConfigWord\(uint cfgIdx, uint wordIdx\) \{[\s\S]*?\n\}/,`uint getConfigWord(uint cfgIdx,uint wordIdx) { return configData[cfgIdx*${model.CONFIG_WORDS}u+wordIdx]; }`);
 shader=replaceOnce(shader,/void main\(\)\{[\s\S]*?uint globalLane=offset\+lane;/,`void computemain(){
 uint lane=gl_GlobalInvocationID.x;
 if(lane>=count)return;
 uint globalLane=offset+lane;`);
 let output=` for(uint word=0u;word<${words}u;word++) resultData[lane*${words}u+word]=outputWord(word);`;
 if(detailed){
  // Explicit stores avoid a large dynamic report switch on software Vulkan.
  // Extract each expression from the source encoder, preserving its exact bits.
  const start=shader.indexOf('uint compactWord(uint index)');
  const stop=shader.indexOf('uint fastWord(uint index)',start);
  const expressions=new Map([...shader.slice(start,stop).matchAll(/case (\d+)u:return ([^;]+);/g)].map(m=>[Number(m[1]),m[2]]));
  if(expressions.size!==words)throw Error('Detailed report expression layout changed');
  output=Array.from({length:words},(_,i)=>` resultData[lane*${words}u+${i}u]=${expressions.get(i)};`).join('\n');
 }
 shader=replaceOnce(shader,/ if\(mode==2u\)\{\n  report0=[\s\S]*?report3=outputFour\(base\+12u\);\}/,output);
 if(/gl_FragCoord|report[0-3]|configTex|uniform |gridWidth/.test(shader)) throw Error('Fragment transport remains');
 fs.writeFileSync(path.join(destination,detailed?'detailed.glsl':'fast.glsl'),`// Generated by tools/import_warlock.mjs. Source hashes in manifest.json.\n${shader}`);
}
const example=model.validate({...model.DEFAULTS,iterations:65,seed:101});
const packedExample=Array.from(model.packConfig(example));
fs.writeFileSync(path.join(destination,'example.lua'),'-- Generated transport fixture only; not a Forever parity scenario.\nreturn {duration='+example.duration+', seed='+example.seed+', iterations='+example.iterations+', configWords='+model.CONFIG_WORDS+', detailedWords='+model.COMPACT_WORDS+', packed={'+packedExample.join(',')+'}}\n');
function lua(value) {
 if(Array.isArray(value)) return '{'+value.map(lua).join(',')+'}';
 if(value && typeof value==='object') return '{'+Object.entries(value).map(([k,v])=>'['+JSON.stringify(k)+']='+lua(v)).join(',')+'}';
 return JSON.stringify(value);
}
function reportFields(detailed) {
 const fields={};
 const field=(name,word,type='u32',part=null)=>fields[name]={word,type,...(part?{part}: {})};
 const pair=(low,high,word)=>{field(low,word,'u32','low');field(high,word,'u32','high');};
 field('total',0,'f32');pair('done','highWater',1);field('events',2);
 pair('taps','procs',3);pair('isbProcs','isbConsumed',4);
 field('petBrandDamage',5,'f32');field('petDamage',6,'f32');pair('petCasts','rngCalls',7);
 const melee=detailed?26:8, spell=detailed?29:11;
 field('petMeleeDamage',melee,'f32');pair('petMeleeCasts','petMeleeHits',melee+1);pair('petMeleeCrits','petMeleeMisses',melee+2);
 field('petSpellDamage',spell,'f32');pair('petSpellCasts','petSpellHits',spell+1);pair('petSpellCrits','petSpellMisses',spell+2);
 if(!detailed){field('mana',14,'f32');field('spent',15,'f32');return fields;}
 for(let i=0;i<model.SPELLS.length;i++){
  const word=i<6?8+i*3:32+(i-6)*3;
  field('damage'+i,word,'f32');pair('casts'+i,'hits'+i,word+1);pair('crits'+i,'misses'+i,word+2);
 }
 model.UPTIME_EFFECTS.forEach(([,key],i)=>field('uptime_'+key,model.DETAIL_WORD_OFFSET+Math.floor(i/2),'fraction',i%2?'high':'low'));
 field('spent',model.DETAIL_WORD_OFFSET+6,'f32');field('manaWasted',model.DETAIL_WORD_OFFSET+7,'f32');
 field('impDamage',model.DETAIL_WORD_OFFSET+8,'f32');pair('impCasts','impHits',model.DETAIL_WORD_OFFSET+9);pair('impCrits','impMisses',model.DETAIL_WORD_OFFSET+10);
 field('petSwapUsed',model.DETAIL_WORD_OFFSET+11);
 model.DETAIL_EXTRA_OUTPUT.forEach(([name,type],i)=>field(name,model.DETAIL_WORD_OFFSET+12+i,type));
 return fields;
}
fs.writeFileSync(path.join(destination,'layout.lua'),'-- Generated with shaders; word offsets are zero-based.\nreturn '+lua({schemaVersion:1,configWords:model.CONFIG_WORDS,endIndex:Object.keys(model.CONFIG).indexOf('end')+1,configTypes:Object.values(model.CONFIG),heapCapacity:model.HEAP_CAPACITY,fastWords:16,detailedWords:model.COMPACT_WORDS,workgroupSize:64,fields:{fast:reportFields(false),detailed:reportFields(true)}})+'\n');
fs.writeFileSync(path.join(destination,'apl.lua'),'-- Generated VM IDs and 1-based packed config offsets.\nreturn '+lua({schemaVersion:1,maxRules:model.MAX_APL_RULES,actions:model.APL_ACTION,conditions:model.APL_COND,header0:model.APL_HEADER0_OFFSET+1,param0:model.APL_PARAM0_OFFSET+1,header1:model.APL_HEADER1_OFFSET+1,param1:model.APL_PARAM1_OFFSET+1})+'\n');
const manifest={schemaVersion:1,status:'generated; runtime and parity unverified',source:{revision:process.argv[3] || null,hashes},config:Object.entries(model.CONFIG),state:Object.entries(model.STATE),fastState:Object.entries(model.FAST_STATE),spells:model.SPELLS,aplActions:model.APL_ACTION,aplConditions:model.APL_COND,configWords:model.CONFIG_WORDS,detailedWords:model.COMPACT_WORDS,fastWords:16,heapCapacity:model.HEAP_CAPACITY,parameters:['numConfigs','fightsPerConfig','seed','offset','count','eventBudget'],workgroupSize:64};
fs.writeFileSync(path.join(destination,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(`Generated fast/detailed compute kernels: ${model.CONFIG_WORDS} config words, ${model.COMPACT_WORDS} detailed result words.`);
